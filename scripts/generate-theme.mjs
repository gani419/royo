import fs from 'node:fs';
const source = new URL('../packages/theme/src/tokens.json', import.meta.url);
const target = new URL('../packages/theme/assets/css/variables.css', import.meta.url);
const tokens = JSON.parse(fs.readFileSync(source, 'utf8'));
const css = `/* Generated by scripts/generate-theme.mjs. Edit src/tokens.json. */\n:root {\n${Object.entries(tokens).map(([key, value]) => `  --${key.replace(/[A-Z]/g, m => `-${m.toLowerCase()}`)}: ${typeof value === 'number' ? `${value}px` : value};`).join('\n')}\n}\n`;
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== css) throw new Error('Shared CSS tokens are out of date. Run node scripts/generate-theme.mjs.');
} else {
  fs.mkdirSync(new URL('../packages/theme/assets/css/', import.meta.url), { recursive: true });
  fs.writeFileSync(target, css);
}
